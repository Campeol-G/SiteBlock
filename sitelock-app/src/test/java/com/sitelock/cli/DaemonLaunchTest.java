package com.sitelock.cli;

import com.sitelock.core.AutostartArtifact;
import com.sitelock.core.AutostartPaths;
import com.sitelock.core.ExpirationDaemonState;
import com.sitelock.core.OsType;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.jar.Attributes;
import java.util.jar.JarOutputStream;
import java.util.jar.Manifest;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The command line that starts the daemon must actually work.
 *
 * <p>This is the test that reproduces the original defect. The systemd unit runs
 * the line generated by {@link AutostartArtifact}; if the line is malformed, the
 * process dies with code 2 and systemd enters a crash loop — which is exactly
 * what happened: thousands of restarts and no daemon running.
 *
 * <p>That is why the test does not check the line with {@code assertEquals} and
 * stop there. It <b>executes</b> the line against a real jar and requires the
 * daemon to come up. An {@code assert} on the shape of the list would pass with
 * {@code java -jar x.jar -Dfoo=1 Main} — which is precisely the broken line.
 */
class DaemonLaunchTest {

    @TempDir
    Path tmp;

    // ---- the command line for the "daemon start" fork ----

    @Test
    void childCommandPutsPropertiesBeforeTheJar() {
        String saved = System.getProperty("siteblock.jar");
        System.setProperty("siteblock.jar", "/opt/sitelock/siteblock.jar");
        try {
            List<String> cmd = new DaemonStartCommand("60", null, null)
                    .buildChildCommand(tmp.resolve("state"), tmp.resolve("hosts"));

            int prop = cmd.indexOf("-Dsitelock.stateDir=" + tmp.resolve("state").toAbsolutePath());
            int jar = cmd.indexOf("-jar");
            assertTrue(prop >= 0 && jar >= 0 && prop < jar,
                    "after -jar the property becomes a program argument and picocli rejects it: " + cmd);
        } finally {
            if (saved == null) {
                System.clearProperty("siteblock.jar");
            } else {
                System.setProperty("siteblock.jar", saved);
            }
        }
    }

    @Test
    void childCommandPinsUtf8ForTheLog() {
        // On Windows the process default is the native code page; the log is read
        // as UTF-8 by tail and by the tests.
        List<String> cmd = new DaemonStartCommand("60", null, null)
                .buildChildCommand(tmp.resolve("state"), tmp.resolve("hosts"));

        assertTrue(cmd.contains("-Dstdout.encoding=UTF-8"), cmd.toString());
        assertTrue(cmd.contains("-Dstderr.encoding=UTF-8"), cmd.toString());
    }

    @Test
    void childCommandWithJarDropsTheMainClass() {
        String saved = System.getProperty("siteblock.jar");
        System.setProperty("siteblock.jar", "/opt/sitelock/siteblock.jar");
        try {
            List<String> cmd = new DaemonStartCommand("60", null, null)
                    .buildChildCommand(tmp.resolve("state"), tmp.resolve("hosts"));

            assertFalse(cmd.contains("com.sitelock.SiteLockApplication"),
                    "with -jar the class name is redundant and breaks the daemon: " + cmd);
        } finally {
            if (saved == null) {
                System.clearProperty("siteblock.jar");
            } else {
                System.setProperty("siteblock.jar", saved);
            }
        }
    }

    // ---- proof that the generated line starts the daemon ----

    @Test
    void theGeneratedCommandActuallyStartsTheDaemon() throws Exception {
        Path jar = buildJar();
        Path hosts = tmp.resolve("hosts");
        Files.writeString(hosts, "127.0.0.1 localhost\n", StandardCharsets.UTF_8);
        Path state = tmp.resolve("state");
        Files.createDirectories(state);

        AutostartPaths paths = new AutostartPaths(
                state, hosts,
                Paths.get(System.getProperty("java.home"), "bin", "java").toString(),
                jar.toString(), "", null, OsType.LINUX);

        List<String> cmd = AutostartArtifact.commandLine(paths);
        Process p = new ProcessBuilder(cmd).redirectErrorStream(true)
                .redirectOutput(ProcessBuilder.Redirect.appendTo(
                        tmp.resolve("daemon.log").toFile()))
                .start();

        try {
            Path daemonJson = ExpirationDaemonState.statePath(state);
            for (int i = 0; i < 150 && !Files.exists(daemonJson); i++) {
                Thread.sleep(100);
            }

            assertTrue(Files.exists(daemonJson),
                    "the daemon did not come up. Line: " + cmd + "\nLog:\n" + log());
            assertTrue(p.isAlive(), "the daemon came up and died:\n" + log());
        } finally {
            p.destroyForcibly();
            p.waitFor();
        }
    }

    private String log() {
        try {
            Path l = tmp.resolve("daemon.log");
            return Files.exists(l) ? Files.readString(l, StandardCharsets.UTF_8) : "(no log)";
        } catch (Exception e) {
            return "(no log)";
        }
    }

    // A real jar, with the manifest's Main-Class and the whole classpath in the
    // Class-Path attribute: the same shape as the fat jar that run.sh uses and
    // that the systemd unit consumes. An empty jar would not exercise -jar.
    private Path buildJar() throws Exception {
        StringBuilder classPath = new StringBuilder();
        for (String entry : System.getProperty("java.class.path").split(File.pathSeparator)) {
            if (entry.isBlank()) {
                continue;
            }
            if (classPath.length() > 0) {
                classPath.append(' ');
            }
            classPath.append(Path.of(entry).toUri());
        }

        Manifest mf = new Manifest();
        mf.getMainAttributes().put(Attributes.Name.MANIFEST_VERSION, "1.0");
        mf.getMainAttributes().put(Attributes.Name.MAIN_CLASS, "com.sitelock.SiteLockApplication");
        mf.getMainAttributes().put(Attributes.Name.CLASS_PATH, classPath.toString());

        Path jar = tmp.resolve("siteblock-test.jar");
        try (JarOutputStream out = new JarOutputStream(Files.newOutputStream(jar), mf)) {
            // WHY: a jar with no entries — the classes come from the manifest's Class-Path.
        }
        return jar;
    }
}
